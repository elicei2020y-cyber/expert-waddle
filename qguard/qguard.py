# ----------------------------------------------------------------- ядро
def _scales(w, qmax, axis=0):
    """Масштаб по максимуму модуля вдоль оси. Без обрезки: правило 4."""
    sc = np.abs(w).max(axis=axis, keepdims=True) / qmax
    return np.where(sc == 0, 1.0, sc)


def _uniform(w, bits):
    qmax = 2 ** (bits - 1) - 1
    sc = _scales(w, qmax)
    return np.clip(np.round(w / sc), -qmax - 1, qmax) * sc


def _codebook(w, bits, iters=25):
    """Уровни по Ллойду-Максу, по столбцу. Замкнутая форма: подгоняется
    под ГИСТОГРАММУ весов, а не под целевую функцию задачи."""
    L = 2 ** bits
    out = np.empty_like(w)
    for j in range(w.shape[1]):
        col = w[:, j]
        c = np.quantile(col, np.linspace(0, 1, L))
        for _ in range(iters):
            a = np.abs(col[:, None] - c[None, :]).argmin(1)
            for i in range(L):
                m = a == i
                if m.any():
                    c[i] = col[m].mean()
        out[:, j] = c[np.abs(col[:, None] - c[None, :]).argmin(1)]
    return out


def quantize(w, bits, codebook=None):
    """Один тензор по рецепту. codebook=None -- решает правило 5."""
    if bits >= 16:
        return w.copy()
    if w.ndim != 2:
        return _uniform(w.reshape(-1, 1), bits).reshape(w.shape)
    use = (bits < 4) if codebook is None else codebook
    return _codebook(w, bits) if use else _uniform(w, bits)


class Recipe:
    """Разрядность одна на все веса: правило 3. Смешивать запрещено."""

    def __init__(self, bits=4, weight_keys=("w1", "w2"),
                 bias_keys=("b1", "b2"), quantize_biases=True):
        if not (2 <= bits <= 16):
            raise ValueError("bits вне 2..16")
        self.bits = bits
        self.weight_keys = tuple(weight_keys)
        self.bias_keys = tuple(bias_keys)
        self.quantize_biases = quantize_biases

    def __repr__(self):
        cb = "кодовая книга" if self.bits < 4 else "равномерная сетка"
        return (f"Recipe(bits={self.bits}, {cb}, масштаб на столбец, "
                f"округление к ближайшему)")


def quantize_all(params, recipe):
    """Все веса по одному рецепту. Смещения -- бесплатно (правило 31)."""
    out = {}
    for k, v in params.items():
        if k in recipe.weight_keys:
            out[k] = quantize(v, recipe.bits)
        elif k in recipe.bias_keys and recipe.quantize_biases:
            out[k] = quantize(v, recipe.bits)
        else:
            out[k] = v.copy()
    return out


# ------------------------------------------------- поправка смещений
def bias_correction(fp_acts, q_acts, bias):
    """Средний сдвиг активаций -- в смещение. Замкнутая форма, без поиска.

    fp_acts, q_acts -- предактивации (до нелинейности) на калибровке,
    полученные неквантованными и квантованными весами.
    Возвращает исправленный вектор смещений.

    Почему именно среднее, а не наименьшие квадраты: измерено, что
    наименьшие квадраты дают МЕНЬШЕ сбитых argmax на калибровке
    и ХУДШИЙ результат при порождении. Прокси не предсказывает исход.
    """
    return bias + (fp_acts - q_acts).mean(axis=0)


# ------------------------------------------------- поворот базиса
def rotation(n, seed=0):
    """Случайная ортогональная матрица. Замкнутая форма, ничего не подгоняет."""
    A = np.random.default_rng(seed).normal(0, 1, (n, n))
    Q, _ = np.linalg.qr(A)
    return Q


def rotate_layer(W, Q):
    """W' = Q^T W. На входе слоя подавать x' = x Q -- тождество точно:
    (xQ)(Q^T W) = xW. Квантуется уже W'.

    ЗАЧЕМ. Обрезка выбросов вредна (они несут сигнал), но выбросы можно
    не резать, а РАЗМАЗАТЬ: поворот снижает max/std с 5.58 до 3.55
    и эксцесс с 5.19 до 3.01, ничего не теряя.

    КОГДА ПОМОГАЕТ. Только при острой нехватке уровней. Из 60 отчётов,
    среднее по восьми случайным поворотам:
        2 бита: 22 -> 36.5   (крупный и надёжный выигрыш)
        3 бита: 47 -> 49.6   (внутри шума)
        4 бита: 53 -> 51.8   (внутри шума)

    ВЫБОР МАТРИЦЫ НЕ ПОДДАЁТСЯ ЗАМКНУТОЙ ФОРМЕ. Все случайные повороты
    статистически неразличимы (max/std 3.505..3.546), а точность гуляет
    от 23 до 41, и ни max/std, ни эксцесс, ни ошибка квантования её
    не предсказывают. Утешение: худший жребий (23) не хуже отсутствия
    поворота (22) -- поворот не вредит никогда.
    """
    return Q.T @ W


# ---------------------------------------------------- голосование
def vote(outputs, keys=None):
    """Большинство по полям между N параллельными выходами.

    СВОЙСТВО, КОТОРОЕ ДЕЛАЕТ ЕГО ЦЕННЫМ: он не знает, по какому признаку
    результат будут проверять, и потому не может подогнать ответ
    под проверку. Все починки, знающие проверку, превращают обнаружимую
    ошибку в необнаружимую; голосование -- нет.

    СВОЙСТВО, КОТОРОЕ ОГРАНИЧИВАЕТ ЕГО ПРИМЕНЕНИЕ: качество голосования
    не выше качества копий. Если копии делаются стохастическим
    округлением, каждая хуже округления к ближайшему, и голосование
    проигрывает одиночной детерминированной модели: 53 -> 49 (4 бита),
    53 -> 4 (3 бита). Нужен источник РАЗНЫХ и при этом ХОРОШИХ копий.
    """
    if not outputs:
        return {}
    ks = keys if keys is not None else sorted({k for o in outputs for k in o})
    res = {}
    for k in ks:
        c = Counter(o[k] for o in outputs if k in o)
        if c:
            res[k] = c.most_common(1)[0][0]
    return res


# ---------------------------------------------------- честность меры
def resolution(n_trials, p_hat=0.85, scale=None, boots=20000, seed=0):
    """Разрешающая способность доли: разницу МЕНЬШЕ неё объявлять нельзя.

    Возвращает (ст.откл. разницы, порог 80%, порог 95%) в единицах scale.
    Мера введена потому, что немонотонный ряд по разрядностям (53, 51,
    54, 52 при 4, 5, 6, 7 битах) показал: различия внутри шума мы
    несколько часов принимали за результат.
    """
    scale = scale or n_trials
    rng = np.random.default_rng(seed)
    a = (rng.random((boots, n_trials)) < p_hat).sum(1)
    b = (rng.random((boots, n_trials)) < p_hat).sum(1)
    d = (a - b) * (scale / n_trials)
    return float(d.std()), float(np.percentile(np.abs(d), 80)), \
        float(np.percentile(np.abs(d), 95))


